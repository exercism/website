#!/usr/bin/env node
// Writes index.ts in this folder, which tells utils/highlight.ts how to load
// each grammar on demand. Run `yarn highlight-grammars` after upgrading
// highlight.js or changing the extra grammars below.
//
// Each grammar registers its own aliases (e.g. "golang" for "go") and names
// the grammars it embeds (e.g. "xml" embeds "css" and "javascript"), but only
// once it has been loaded. This script registers every grammar up front so it
// can record both, letting the browser fetch the right files before
// highlighting.

import fs from "fs";
import path from "path";
import { createRequire } from "module";
import { fileURLToPath } from "url";
import prettier from "prettier";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));

// Grammars for languages that highlight.js doesn't ship. Each one is registered
// under the name given here, so tracks can use it as their highlightjs_language.
// If two grammars claim the same alias, the later one wins, matching the order
// in which highlight.js registers languages.
const EXTRA_GRAMMARS = [
  ["abap", "highlightjs-sap-abap"],
  ["arturo", "@exercism/highlightjs-arturo"],
  ["cobol", "highlightjs-cobol"],
  ["bqn", "highlightjs-bqn"],
  ["zig", "highlightjs-zig"],
  ["lean", "highlightjs-lean"],
  ["gleam", "@gleam-lang/highlight.js-gleam"],
  ["chapel", "highlightjs-chapel"],
  ["gdscript", "@exercism/highlightjs-gdscript"],
  ["jq", "highlightjs-jq"],
  ["uiua", "@exercism/highlightjs-uiua"],
  ["jikiscript", "@exercism/highlightjs-jikiscript"],
  ["futhark", "@exercism/highlightjs-futhark"],
  ["odin", "@exercism/highlightjs-odin"],
  ["sqlite", "@exercism/highlightjs-sqlite"],
  ["euphoria", "@exercism/highlightjs-euphoria"],
  ["factor", "@exercism/highlightjs-factor"],
  ["8th", "@exercism/highlightjs-8th"],
  ["roc", "@exercism/highlightjs-roc"],
  ["yamlscript", "@exercism/highlightjs-yamlscript"],
  ["raku", "@exercism/highlightjs-raku"],
  ["cairo", "@exercism/highlightjs-cairo"],
  ["vlang", "@exercism/highlightjs-v"],
  ["purescript", "@exercism/highlightjs-purescript"],
  ["unison", "@exercism/highlightjs-unison"],
  ["idris", "@exercism/highlightjs-idris"],
  ["cfml", "@exercism/highlightjs-cfml"],
  ["racket", "@exercism/highlightjs-racket"],
  ["lfe", "@exercism/highlightjs-lfe"],
  ["rescript", "highlightjs-rescript"],
  ["pyret", "@exercism/highlightjs-pyret"],
  ["red", "highlightjs-redbol"],
  ["ballerina", "@ballerina/highlightjs-ballerina"],
];

// highlight.js's own index registers its languages in this order.
function builtInGrammars() {
  const index = fs.readFileSync(require.resolve("highlight.js"));
  return [...index.toString().matchAll(/registerLanguage\('([^']+)'/g)].map(
    ([, name]) => [name, `highlight.js/lib/languages/${name}`]
  );
}

async function loadGrammar(specifier) {
  const module = await import(require.resolve(specifier));
  return module.default.default || module.default;
}

function subLanguagesOf(definition) {
  const found = new Set();
  const seen = new Set();
  const visit = (value) => {
    if (value === null || typeof value !== "object" || seen.has(value)) return;
    seen.add(value);
    if (value instanceof RegExp) return;

    const sub = value.subLanguage;
    if (typeof sub === "string") found.add(sub);
    if (Array.isArray(sub)) sub.forEach((name) => found.add(name));

    Object.values(value).forEach(visit);
  };
  visit(definition);
  return [...found];
}

async function main() {
  const hljs = require("highlight.js/lib/core");
  const grammars = [...builtInGrammars(), ...EXTRA_GRAMMARS];

  for (const [name, specifier] of grammars) {
    hljs.registerLanguage(name, await loadGrammar(specifier));
  }

  const names = grammars.map(([name]) => name);
  const canonical = (name) => {
    const lower = name.toLowerCase();
    if (names.includes(lower)) return lower;
    const language = hljs.getLanguage(lower);
    return names.find((n) => hljs.getLanguage(n) === language);
  };

  const aliases = {};
  for (const name of names) {
    for (const alias of hljs.getLanguage(name).aliases || []) {
      const lower = alias.toLowerCase();
      if (lower !== name && !names.includes(lower)) aliases[lower] = name;
    }
  }

  const entries = grammars.map(([name, specifier]) => {
    const requires = subLanguagesOf(hljs.getLanguage(name))
      .map(canonical)
      .filter((dependency) => dependency && dependency !== name);
    const load = `load: () => import('${specifier}')`;
    const deps = requires.length
      ? `, requires: ${JSON.stringify(requires)}`
      : "";
    return `  ${JSON.stringify(name)}: { ${load}${deps} },`;
  });

  const source = `// Generated by app/javascript/utils/highlight-grammars/generate.mjs.
// Don't edit this file by hand. Run \`yarn highlight-grammars\` instead.
import type { LanguageFn } from 'highlight.js'

export type Grammar = {
  load: () => Promise<{ default: LanguageFn }>
  requires?: string[]
}

export const grammars: Record<string, Grammar> = {
${entries.join("\n")}
}

export const aliases: Record<string, string> = ${JSON.stringify(aliases)}
`;

  const outputPath = path.join(here, "index.ts");
  const options = (await prettier.resolveConfig(outputPath)) || {};
  const formatted = await prettier.format(source, {
    ...options,
    filepath: outputPath,
  });
  fs.writeFileSync(outputPath, formatted);
  console.log(
    `Wrote ${names.length} grammars and ${
      Object.keys(aliases).length
    } aliases to ${path.relative(process.cwd(), outputPath)}`
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
